import { test } from "node:test";
import assert from "node:assert/strict";
import { findBan, findIssues, formatFind, openLinkedPrs, scopeReason, skipReason } from "../src/find.mjs";

test("spots refusals of AI contributions and ignores neutral text", () => {
  assert.match(findBan("We do not accept pull requests generated by AI tools."), /do not accept/);
  assert.match(findBan("LLM-generated code is not accepted here."), /LLM-generated/);
  assert.equal(findBan("Please disclose AI assistance with an Assisted-by trailer."), null);
  assert.equal(findBan(null), null);
});

test("finds only open pull requests that reference the issue", () => {
  const pr = (state) => ({
    event: "cross-referenced",
    source: { issue: { pull_request: {}, state, html_url: `https://x/pr-${state}` } },
  });
  const issueRef = { event: "cross-referenced", source: { issue: { state: "open", html_url: "https://x/i" } } };
  assert.deepEqual(openLinkedPrs([pr("open"), pr("closed"), issueRef]), ["https://x/pr-open"]);
});

test("gives a reason for every skip", () => {
  const issue = { assignees: [], labels: [] };
  const repo = { archived: false };
  assert.equal(skipReason({ issue, repo, ban: null, linkedPrs: [] }), null);
  assert.equal(skipReason({ issue, repo: { archived: true }, ban: null, linkedPrs: [] }), "repository archived");
  assert.match(skipReason({ issue: { ...issue, assignees: [{ login: "ann" }] }, repo, ban: null, linkedPrs: [] }), /ann/);
  assert.match(
    skipReason({ issue: { ...issue, labels: [{ name: "good first issue" }] }, repo, ban: null, linkedPrs: [] }),
    /good first issue/,
  );
  assert.match(skipReason({ issue, repo, ban: null, linkedPrs: ["https://x/pr"] }), /open PR/);
  assert.match(skipReason({ issue, repo, ban: { file: "AI_POLICY.md", quote: "no AI" }, linkedPrs: [] }), /AI_POLICY/);
});

test("filters out spikes, research and large tasks", () => {
  const issue = (title, labels = [], body = "") => ({ title, labels: labels.map((name) => ({ name })), body });
  assert.match(scopeReason(issue("spike(core): what HTTP over stdio would remove")), /not a fix/);
  assert.match(scopeReason(issue("Improve docs", ["research"])), /"research"/);
  assert.match(scopeReason(issue("Should we drop Node 18?")), /question/);
  assert.match(scopeReason(issue("Decompile the German version of the game")), /whole-project/);
  assert.match(scopeReason(issue("Speed up build", ["size: XL"])), /"size: XL"/);
  assert.match(scopeReason(issue("Clean up", [], "- [ ] a\n- [ ] b\n- [ ] c\n- [ ] d\n- [ ] e\n- [x] f")), /6-item/);
  assert.equal(scopeReason(issue("dom form names every form after the page heading", ["priority: medium", "agent-friendly"])), null);
  assert.equal(scopeReason(issue("Stop Electron requesting keychain access on start up", ["ai-welcome", "size: S"])), null);
});

test("searches each label and groups the output", async () => {
  const github = {
    searchIssues: async (q) => ({
      items: q.includes("agent-friendly")
        ? [{ number: 1, title: "Fix it", html_url: "https://g/o/r/issues/1", repository_url: "https://api.github.com/repos/o/r", assignees: [], labels: [] }]
        : [],
    }),
    repo: async () => ({ archived: false, stargazers_count: 42 }),
    file: async () => null,
    timeline: async () => [],
  };
  const results = await findIssues(github);
  assert.equal(results.length, 1);
  assert.equal(results[0].skip, null);
  const text = formatFind(results);
  assert.match(text, /## Invited with spare-quota-welcome\n\nNone found\./);
  assert.match(text, /Would offer \(1\):\n- https:\/\/g\/o\/r\/issues\/1 \[agent-friendly, 42★\] Fix it/);
});
